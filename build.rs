//! Embeds the Compensating Scaffolding defaults (`cs/<model>/*.toml`) into
//! the binary, so it never depends on a repo checkout (docs/rfc/0002).
//! Every TOML file one directory below `cs/` is included; adding one needs
//! no code change.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("set by cargo")).join("cs");
    // A directory: cargo rescans everything under it for changes.
    println!("cargo:rerun-if-changed={}", root.display());

    let mut files = Vec::new();
    if let Ok(dirs) = std::fs::read_dir(&root) {
        for dir in dirs.flatten().map(|d| d.path()).filter(|p| p.is_dir()) {
            let Ok(entries) = std::fs::read_dir(&dir) else {
                continue;
            };
            for path in entries.flatten().map(|e| e.path()) {
                if path.extension().is_some_and(|e| e == "toml") && path.is_file() {
                    files.push(path);
                }
            }
        }
    }
    files.sort();

    let mut out = String::from(
        "/// Built-in cs files: (path under `cs/`, contents). Generated by build.rs.\n\
         pub(crate) const BUILTIN: &[(&str, &str)] = &[\n",
    );
    for path in &files {
        let name = path.strip_prefix(&root).unwrap_or(path).to_string_lossy();
        let _ = writeln!(
            out,
            "    ({:?}, include_str!({:?})),",
            name,
            path.to_string_lossy()
        );
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("set by cargo")).join("cs_builtin.rs");
    std::fs::write(dest, out).expect("write cs_builtin.rs");
}
